export function stationAbbrFromStopId(stopId: string): string | undefined {
  const raw = String(stopId ?? "").trim()
  if (!raw) return undefined
  const upper = raw.toUpperCase()
  if (PLATFORM_TO_STATION[raw]) return PLATFORM_TO_STATION[raw]
  if (PLATFORM_TO_STATION[upper]) return PLATFORM_TO_STATION[upper]
  // Already a station abbr (legacy feeds)
  if (/^[A-Z0-9]{4}$/.test(upper)) return upper
  // Platform pattern PREFIX-N → try without suffix via map only
  return undefined
}
